//=============================================================================
// TextUtil.h
//
// 日志排版辅助函数。
//
// 存在的原因：printf 的 "%-24s" 是按**字符个数**补齐的，而中文字符在等宽
// 字体下占 2 个字符宽度，直接用 %-24s 会导致中英混排的日志列对不齐。
// 这里按显示宽度（东亚宽字符记 2 列）重新实现补齐。
//=============================================================================

#pragma once

#include <string>

namespace TextUtil
{
    // 计算字符串在等宽字体下占用的列数（东亚全角字符按 2 列计算）。
    size_t DisplayWidth(const std::wstring& text);

    // 在右侧补空格，使字符串占满指定列数；若已超出则原样返回。
    std::wstring PadRight(const std::wstring& text, size_t columns);
}
